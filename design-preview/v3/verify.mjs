import { chromium } from '@playwright/test';
const browser = await chromium.launch({ headless: true });
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
const errors = [];
page.on('pageerror', error => errors.push(error.message));
page.on('console', message => { if (message.type() === 'error') errors.push(message.text()); });
await page.goto('http://127.0.0.1:4173/design-preview/v3/', { waitUntil: 'networkidle' });
await page.waitForTimeout(1500);
console.log('canvases', await page.locator('canvas').count());
console.log('fallback visible', await page.locator('.model-fallback').isVisible());
await page.screenshot({ path: 'design-preview/v3/desktop.png', fullPage: true });
await page.locator('.dish-copy').first().click();
await page.getByRole('button', { name: '双份芝士' }).click();
await page.locator('#plus').click();
await page.locator('#add-order').click();
console.log('cart count', await page.locator('#bag-count').textContent());
await page.locator('.bag').click();
console.log('cart summary', await page.locator('.cart-summary').innerText());
await page.locator('#submit-order').click();
console.log('result', await page.locator('.result h1').innerText());
await page.setViewportSize({ width: 390, height: 844 });
await page.locator('.result [data-page="menu"]').click();
await page.screenshot({ path: 'design-preview/v3/mobile.png', fullPage: true });
console.log('errors', JSON.stringify(errors));
await browser.close();
if (errors.length) process.exitCode = 1;
